
import { useState } from 'react'
import './App.css'

import Sidebar from './components/sidebar'
import MessageBubble from './components/Messagebubble'
import ChatInput from './components/ChatInput'

function App() {
  const [input, setInput] = useState('')
  const [messages, setMessages] = useState([])
  const [isThinking, setIsThinking] = useState(false)

  function handleSend() {
    const question = input.trim()

    if (!question || isThinking) {
      return
    }

    const userMessage = {
      id: Date.now(),
      role: 'user',
      content: question
    }

    setMessages((previousMessages) => [
      ...previousMessages,
      userMessage
    ])

    setInput('')
    setIsThinking(true)

    // Temporary demo response. Real AI comes later.
    setTimeout(() => {
      const aiMessage = {
        id: Date.now() + 1,
        role: 'assistant',
        content:
          'I received your question! In a later development stage, AlgoMind will retrieve relevant DSA knowledge and generate an AI-powered explanation.'
      }

      setMessages((previousMessages) => [
        ...previousMessages,
        aiMessage
      ])

      setIsThinking(false)
    }, 700)
  }

  return (
    <div className="app-layout">
      <Sidebar />

      <main className="chat-main">
        <header className="chat-header">
          <div>
            <h1>AlgoMind</h1>
            <p>Your AI-powered DSA learning companion</p>
          </div>

          <span className="status-indicator">
            Demo mode
          </span>
        </header>

        <section className="messages-area">
          {messages.length === 0 ? (
            <div className="welcome-screen">
              <div className="welcome-icon">A</div>

              <h2>Think better. Code smarter.</h2>

              <p>
                Ask AlgoMind about algorithms, data structures,
                complexity analysis, or coding problems.
              </p>

              <div className="suggestion-list">
                <button
                  onClick={() =>
                    setInput('Explain binary search in Java')
                  }
                >
                  Explain binary search in Java
                </button>

                <button
                  onClick={() =>
                    setInput('What is the time complexity of merge sort?')
                  }
                >
                  Time complexity of merge sort
                </button>

                <button
                  onClick={() =>
                    setInput('Give me a hint for two sum')
                  }
                >
                  Give me a hint for Two Sum
                </button>
              </div>
            </div>
          ) : (
            <div className="message-list">
              {messages.map((message) => (
                <MessageBubble
                  key={message.id}
                  message={message}
                />
              ))}

              {isThinking && (
                <p className="thinking-indicator">
                  AlgoMind is preparing a demo response...
                </p>
              )}
            </div>
          )}
        </section>

        <footer className="chat-footer">
          <ChatInput
            input={input}
            setInput={setInput}
            onSend={handleSend}
            disabled={isThinking}
          />

          <p className="footer-note">
            Demo interface — responses are not generated by AI yet.
          </p>
        </footer>
      </main>
    </div>
  )
}

export default App
